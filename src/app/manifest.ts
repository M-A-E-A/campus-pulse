import type { MetadataRoute } from "next";
import { getT } from "@/i18n/server";

/**
 * The install manifest (linked automatically by the file convention).
 *
 * Localised name/description like every other piece of metadata in this app —
 * the install prompt a French student sees should read French, Arabic RTL, etc.
 * short_name stays a proper noun in all three, since it's the brand under the
 * icon on the home screen.
 *
 * Two icon entries are required for Chrome's installability check (192+512);
 * the maskable one is separate on purpose — Android crops round home-screen
 * icons to a safe circle, and a mark drawn for a square tile would be clipped
 * there. Generated by scripts/gen-pwa-icons.mjs from the Logo.tsx mark.
 */
export default async function manifest(): Promise<MetadataRoute.Manifest> {
  const t = await getT();
  return {
    name: t("meta.title"),
    short_name: "Campus Pulse",
    description: t("meta.description"),
    start_url: "/",
    scope: "/",
    display: "standalone", // the browser's own chrome, no tabs — it should feel like an app
    background_color: "#faf7f2", // paper: what paints before the first paint
    theme_color: "#14130f", // ink: matches the viewport themeColor in layout.tsx
    icons: [
      { src: "/icons/icon-192.png", sizes: "192x192", type: "image/png" },
      { src: "/icons/icon-512.png", sizes: "512x512", type: "image/png" },
      {
        src: "/icons/icon-maskable-512.png",
        sizes: "512x512",
        type: "image/png",
        purpose: "maskable",
      },
    ],
  };
}
